// Generates packages/api/seeds/0003_trending_wave1.sql from packages/api/content/wave1.json.
// Rows are inserted as 'draft' and the source has cleared_at NULL, so the serving gate keeps them hidden.
import { readFileSync, writeFileSync } from 'node:fs';
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const data = JSON.parse(readFileSync('packages/api/content/wave1.json', 'utf8'));
const s = data.source;
let sql = `-- GENERATED by scripts/build-wave1-seed.mjs. Do not edit by hand.\n-- Original untested drafts. Not applied to production by this file's existence.\n`;
sql += `INSERT INTO sources (id, name, url, license, cleared_at, notes) VALUES (${q(s.id)}, ${q(s.name)}, ${q(s.url)}, ${q(s.license)}, NULL, ${q(s.notes)});\n`;
for (const r of data.recipes) {
  sql += `INSERT INTO recipes (id, source_id, origin_country) VALUES (${q(r.id)}, ${q(s.id)}, ${q(r.origin_country)});\n`;
  sql += `INSERT INTO recipe_locales (recipe_id, country, lang, title, slug, intro, ingredients_json, steps_json, status) VALUES (${q(r.id)}, ${q(r.country)}, ${q(r.lang)}, ${q(r.title)}, ${q(r.slug)}, ${q(r.intro)}, ${q(JSON.stringify(r.ingredients))}, ${q(JSON.stringify(r.steps))}, 'draft');\n`;
}
writeFileSync('packages/api/seeds/0003_trending_wave1.sql', sql);
